"""
Async Batch Execution & Tracing for the Module 6 Evaluation pipeline.

Reads the synthetic QA dataset from ``artifacts/test_dataset.csv`` (all 25
items), processes every question through the full online
``FinancialRAGPipeline.query()``, and captures the evaluation trace:
    - ``question``:      original question
    - ``ground_truth``:  reference answer from the synthetic dataset
    - ``contexts``:      raw chunks (post-reranker) fed to the LLM
    - ``answer``:        LLM response generated by the pipeline
    - ``model_used``:    generation model that produced the answer
    - ``pipeline_run_id``: pipeline run identifier for traceability

The combined trace is saved strictly to ``artifacts/evaluation_results.csv``.
"""

from __future__ import annotations

import asyncio
import json
from pathlib import Path
from typing import Any, Optional

import pandas as pd

from config.logging_config import get_logger
from config.settings import (
    EVALUATION_RESULTS_PATH,
    EVALUATION_TRACE_COLUMNS,
    SYNTHETIC_BATCH_CONCURRENCY,
    TEST_DATASET_PATH,
)

logger = get_logger("evaluation.batch_runner")


class BatchRunner:
    """
    Executes every question in the synthetic test set through the live RAG
    pipeline and persists the traced responses for offline scoring.

    Uses a bounded asyncio.Semaphore so at most ``concurrency`` pipeline calls
    run in parallel (each offloaded to a worker thread because the pipeline's
    synchronous ``query()`` blocks the event loop).
    """

    def __init__(
        self,
        pipeline: Any,
        input_path: Optional[Path] = None,
        output_path: Optional[Path] = None,
        concurrency: int = SYNTHETIC_BATCH_CONCURRENCY,
        top_k: int = 3,
    ):
        """
        Args:
            pipeline: A ``FinancialRAGPipeline`` instance (mocked in tests).
            input_path: Path to the synthetic QA CSV (default TEST_DATASET_PATH).
            output_path: Path for the traced results CSV (default EVALUATION_RESULTS_PATH).
            concurrency: Max number of parallel pipeline executions.
            top_k: Number of documents to retrieve per question.
        """
        if not hasattr(pipeline, "query"):
            raise TypeError(
                "BatchRunner requires an object exposing query() -- "
                "expected a FinancialRAGPipeline instance."
            )
        self._pipeline = pipeline
        self._input_path = input_path or Path(TEST_DATASET_PATH)
        self._output_path = output_path or Path(EVALUATION_RESULTS_PATH)
        self._concurrency = max(1, int(concurrency))
        self._top_k = top_k

    # -- Dataset I/O ---------------------------------------------------------

    def load_test_dataset(self, path: Optional[Path] = None) -> pd.DataFrame:
        """
        Read and validate the synthetic QA dataset.

        Args:
            path: Override the input CSV path.

        Returns:
            DataFrame with ``question`` and ``ground_truth`` columns.

        Raises:
            FileNotFoundError: When the CSV does not exist.
            ValueError: When required columns are missing.
        """
        p = path or self._input_path
        if not Path(p).exists():
            raise FileNotFoundError(
                f"Synthetic test dataset not found at {p}. Run "
                "SyntheticDataGenerator.generate() first."
            )
        df = pd.read_csv(p)
        missing = [c for c in ("question", "ground_truth") if c not in df.columns]
        if missing:
            raise ValueError(
                f"Test dataset is missing required columns {missing}. "
                f"Got columns: {list(df.columns)}"
            )
        df = df.dropna(subset=["question", "ground_truth"]).reset_index(drop=True)
        return df

    def save(self, df: pd.DataFrame) -> None:
        """Persist the combined evaluation trace to the output CSV."""
        self._output_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(self._output_path, index=False)
        logger.info(
            "Saved %d evaluation traces to %s",
            len(df),
            self._output_path,
        )

    # -- Single-item execution ----------------------------------------------

    @staticmethod
    def _serialize_contexts(contexts: list[dict]) -> str:
        """
        Serialize the raw post-reranker chunks into a compact JSON string.

        Keeps the full chunk payload (text, metadata, rerank_score when the
        Module 4 post-retrieval stage is enabled) so the judge tier has both
        the retrieved text and provenance metadata for scoring.
        """
        if not contexts:
            return "[]"
        slim = []
        for ctx in contexts:
            slim.append({
                "text": ctx.get("text", ""),
                "metadata": ctx.get("metadata", {}),
                "score": ctx.get("score"),
                "rerank_score": ctx.get("rerank_score"),
            })
        return json.dumps(slim, ensure_ascii=False)

    def _run_one(self, question: str, ground_truth: str) -> dict[str, Any]:
        """
        Run a single question through the pipeline and build the trace row.

        Args:
            question: The synthetic question.
            ground_truth: The reference answer.

        Returns:
            Trace dict matching EVALUATION_TRACE_COLUMNS.
        """
        try:
            # Each dataset row is an independent query: drop any accumulated
            # conversation memory so prior contexts never inflate the request
            # past the Groq TPM cap (6000 tokens/minute for the 8b primary).
            reset = getattr(self._pipeline, "reset_memory", None)
            if callable(reset):
                reset()
            result = self._pipeline.query(user_query=question, top_k=self._top_k)
        except Exception as exc:
            logger.error("Pipeline query failed for %r: %s", question[:80], exc)
            result = {}

        parsed = result.get("parsed")
        if parsed is not None:
            answer = getattr(parsed, "answer", "") or ""
        else:
            answer = result.get("raw_output", "")

        contexts = list(getattr(self._pipeline, "_last_contexts", []) or [])

        trace = {
            "question": question,
            "ground_truth": ground_truth,
            "contexts": self._serialize_contexts(contexts),
            "answer": answer,
            "model_used": result.get("model_used", "unknown"),
            "pipeline_run_id": result.get("pipeline_run_id", ""),
        }
        logger.info(
            "Traced question: %s (model=%s, contexts=%d)",
            question[:60],
            trace["model_used"],
            len(contexts),
        )
        return trace

    # -- Async batch loop ----------------------------------------------------

    async def arun_batch(self) -> pd.DataFrame:
        """
        Async execution loop over the full test dataset.

        Processes all rows in the CSV (bounded by the concurrency semaphore)
        and returns the combined trace DataFrame.
        """
        df = self.load_test_dataset()
        semaphore = asyncio.Semaphore(self._concurrency)

        async def _bounded(row) -> dict[str, Any]:
            async with semaphore:
                return await asyncio.to_thread(
                    self._run_one,
                    str(row["question"]),
                    str(row["ground_truth"]),
                )

        traces = await asyncio.gather(
            *[_bounded(row) for _, row in df.iterrows()]
        )
        result_df = pd.DataFrame(traces, columns=list(EVALUATION_TRACE_COLUMNS))
        self.save(result_df)
        return result_df

    def run(self) -> pd.DataFrame:
        """Synchronous wrapper around the async batch loop."""
        return asyncio.run(self.arun_batch())
